"""PRAM images: build from source, save/load in the formats hosts use."""
import json, os

from . import asm, chip, isa

RUNTIME = os.path.join(asm.SDK_INCLUDE, 'runtime.asm')
FORMAT = 'sxplug-image-1'


class Image:
    def __init__(self, words, base=chip.PRAM_BASE, symbols=None, name='plugin', lines=None,
                 labels=()):
        self.labels = set(labels)
        self.words = list(words)
        self.base = base
        self.symbols = dict(symbols or {})
        self.name = name
        self.lines = lines or []

    def __len__(self):
        return len(self.words)

    def word(self, addr):
        i = addr - self.base
        return self.words[i] if 0 <= i < len(self.words) else None

    # ---------------------------------------------------------------- output
    def to_json(self):
        return json.dumps({'format': FORMAT, 'name': self.name, 'base': self.base,
                           'words': ['%06x' % w for w in self.words],
                           'symbols': {k: v for k, v in sorted(self.symbols.items())},
                           'labels': sorted(self.labels)}, indent=1)

    def to_bin(self):
        """Exactly the bytes written to 0x8000.. (4 bytes per word, big-endian)."""
        return b''.join(w.to_bytes(4, 'big') for w in self.words)

    def to_c(self, ident=None):
        """C header. Works with sxplug_load() and RadioLib's uploadPatch(arr, sizeof(arr))."""
        ident = ident or c_ident(self.name)
        out = ['// Generated by sxplug from %s. PRAM image for SX126x ROM "%s".'
               % (self.name, chip.ROM_VERSION.decode()),
               '// Load: sxplug_load(io, %s, %s_WORDS, 1)' % (ident, ident.upper()),
               '//   or RadioLib: radio.uploadPatch(%s, sizeof(%s))' % (ident, ident),
               '#pragma once', '#include <stdint.h>', '',
               '#define %s_WORDS %d' % (ident.upper(), len(self.words)), '']
        for k in ('SX_TAG',):
            if k in self.symbols:
                out.append('#define %s_%s 0x%02X' % (ident.upper(), k, self.symbols[k]))
        out += ['', 'static const uint32_t %s[%d] = {' % (ident, len(self.words))]
        for i in range(0, len(self.words), 8):
            out.append('  ' + ' '.join('0x%06x,' % w for w in self.words[i:i + 8]))
        out += ['};', '']
        return '\n'.join(out)

    def to_var(self):
        """Semtech sx1302_hal format (`const uint32_t pram[]` + PRAM_COUNT)."""
        return ('const uint32_t pram[] = {\n' + ',\n'.join('0x%x' % w for w in self.words)
                + '\n};\n\n#define PRAM_COUNT %d' % len(self.words))

    def listing(self):
        at = {}
        for k in sorted(self.labels):
            v = self.symbols.get(k)
            if v is not None and self.base <= v <= self.base + len(self.words):
                at.setdefault(v, []).append(k)
        if not at:                         # no symbols (loaded from .h/.var/.bin): name targets
            for w in self.words:
                r = isa.disasm(w)[1]
                if r and self.base <= r[1] < self.base + len(self.words):
                    at.setdefault(r[1], ['l_%04x' % r[1]])
        src = {a: '%s  %s' % (where, text) for a, ws, where, text in self.lines}
        out = []
        for i, w in enumerate(self.words):
            a = self.base + i
            for nm in at.get(a, []):
                out.append('%s:' % nm)
            txt, ref = isa.disasm(w)
            if ref and ref[1] in at:
                txt += ' <%s>' % at[ref[1]][0]
            out.append('  %04x: %06x  %-40s %s' % (a, w, txt, src.get(a, '')))
        return '\n'.join(out) + '\n'

    def save(self, stem, formats=('json', 'h', 'bin', 'lst')):
        written = []
        for f in formats:
            p = '%s.%s' % (stem, f)
            if f == 'bin':
                data = self.to_bin()
                with open(p, 'wb') as fh:
                    fh.write(data)
            else:
                text = {'json': self.to_json, 'h': self.to_c, 'var': self.to_var,
                        'lst': self.listing}[f]()
                with open(p, 'w') as fh:
                    fh.write(text)
            written.append(p)
        return written


def c_ident(name):
    s = ''.join(ch if ch.isalnum() else '_' for ch in os.path.splitext(os.path.basename(name))[0])
    return ('pram_' + s) if not s[:1].isalpha() else s + '_pram'


def build(path, include_dirs=(), defines=None, runtime=True):
    """Assemble a plugin source file into an Image.

    runtime=True prepends include/runtime.asm (entry table + defaults); use False
    for a source that lays out 0x8000.. itself (e.g. examples/semtech)."""
    path = os.path.abspath(path)
    if runtime:
        text = '.include "%s"\n.include "%s"\n' % (RUNTIME, path)
        prog = asm.assemble(text, path='<build>', include_dirs=[os.path.dirname(path)] + list(include_dirs),
                            defines=defines)
    else:
        prog = asm.assemble(path=path, include_dirs=include_dirs, defines=defines)
    if len(prog.words) > chip.PRAM_WORDS:
        raise asm.AsmError('image is %d words, PRAM holds %d' % (len(prog.words), chip.PRAM_WORDS))
    return Image(prog.words, prog.base, prog.symbols, os.path.basename(path), prog.lines, prog.labels)


def load(path):
    """Load an image from .json, .h/.var (C array) or .bin."""
    ext = os.path.splitext(path)[1].lower()
    name = os.path.basename(path)
    if ext == '.json':
        d = json.load(open(path))
        if d.get('format') != FORMAT:
            raise ValueError('%s: not an sxplug image' % path)
        img = Image([int(w, 16) for w in d['words']], d['base'], d.get('symbols'), d.get('name', name),
                    labels=d.get('labels', ()))
        return img
    if ext == '.bin':
        data = open(path, 'rb').read()
        if len(data) % 4:
            raise ValueError('%s: size is not a multiple of 4' % path)
        return Image([int.from_bytes(data[i:i + 4], 'big') for i in range(0, len(data), 4)], name=name)
    import re
    txt = open(path).read()
    body = txt.split('{', 1)[1].split('}')[0] if '{' in txt else txt
    body = re.sub(r'//[^\n]*|/\*.*?\*/', '', body, flags=re.S)
    return Image([int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]+)', body)], name=name)
